-- This does not change the existing ASSIST agreements/institutions tables.
CREATE TABLE IF NOT EXISTS pathway_users (
  user_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email TEXT NOT NULL UNIQUE,
  password_hash TEXT,
  google_sub TEXT UNIQUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT pathway_has_login_method CHECK (password_hash IS NOT NULL OR google_sub IS NOT NULL)
);
